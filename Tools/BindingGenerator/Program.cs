try
{
    // Rewrite legacy compilation inputs while keeping shared declarations authoritative.
    if (args is ["--self-test"])
    {
        GeneratorTests.Run();
        return;
    }

    if (args.Length < 2 || args.Length > 3)
    {
        throw new ArgumentException("Expected source/output directories and optional compilation symbols, or --self-test.");
    }

    string sourceDirectory = Path.GetFullPath(args[0]);
    string outputDirectory = Path.GetFullPath(args[1]);
    var comparison = OperatingSystem.IsWindows() ? StringComparison.OrdinalIgnoreCase : StringComparison.Ordinal;

    if (sourceDirectory.Equals(outputDirectory, comparison) || outputDirectory.StartsWith(sourceDirectory + Path.DirectorySeparatorChar, comparison))
    {
        throw new ArgumentException("Generated files must be outside the source directory.");
    }

    Directory.CreateDirectory(outputDirectory);
    var generatedPaths = new HashSet<string>(OperatingSystem.IsWindows() ? StringComparer.OrdinalIgnoreCase : StringComparer.Ordinal);
    string[]? symbols = args.Length == 3 ? args[2].Split(';', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries) : null;
    int count = 0;

    // Stable traversal also makes generated delegate numbering reproducible across build hosts.
    foreach (string path in Directory.GetFiles(sourceDirectory, "*.cs", SearchOption.AllDirectories).Order(StringComparer.Ordinal))
    {
        string output = Path.Combine(outputDirectory, Path.GetRelativePath(sourceDirectory, path));
        string generated = BindingSource.Generate(File.ReadAllText(path), out int imports, symbols);
        generatedPaths.Add(output);
        Directory.CreateDirectory(Path.GetDirectoryName(output)!);

        // Stable content preserves compiler incrementality even when the generator runs again.
        if (!File.Exists(output) || File.ReadAllText(output) != generated)
        {
            File.WriteAllText(output, generated);
        }

        count += imports;
    }

    if (count == 0)
    {
        throw new InvalidOperationException("No HDF5 imports found.");
    }

    // Remove only obsolete files produced by this generator.
    foreach (string stale in Directory.GetFiles(outputDirectory, "*.cs", SearchOption.AllDirectories))
    {
        if (!generatedPaths.Contains(stale) && File.ReadLines(stale).FirstOrDefault() == "// <auto-generated/>")
        {
            File.Delete(stale);
        }
    }

    Console.WriteLine($"Generated {count} legacy bindings from shared declarations.");
}
catch (Exception error)
{
    Console.Error.WriteLine(error);
    Environment.ExitCode = 1;
}
