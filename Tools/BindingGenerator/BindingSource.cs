using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

/// <summary>
/// Transforms shared declarations into legacy compilation inputs while preserving source metadata.
/// </summary>
internal static class BindingSource
{
    /// <summary>
    /// Defines the default legacy preprocessor symbols used when no build symbols are supplied.
    /// </summary>
    private static readonly CSharpParseOptions Options = new CSharpParseOptions(LanguageVersion.Latest)
        .WithPreprocessorSymbols("NETSTANDARD", "NETSTANDARD2_0");

    /// <summary>
    /// Rewrites native imports and UTF-8 annotations, then validates the generated syntax.
    /// </summary>
    internal static string Generate(string source, out int count, IEnumerable<string>? symbols = null,
        CSharpParseOptions? parseOptions = null, CancellationToken cancellationToken = default, string path = "")
    {
        // Parse with the consuming build's symbols so inactive branches never become active bindings.
        var options = parseOptions ?? Options;

        if (symbols != null)
        {
            options = options.WithPreprocessorSymbols(symbols);
        }

        var tree = CSharpSyntaxTree.ParseText(source, options, path, cancellationToken: cancellationToken);
        Validate(tree, cancellationToken);
        var original = tree.GetRoot(cancellationToken);

        // Validate ownership before rewriting so errors retain the original input's source coordinates.
        new UTF8Marshalling(cancellationToken).Visit(original);

        // Content identity avoids partial-class name collisions without embedding machine-specific paths.
        string identity;
        using (var hash = System.Security.Cryptography.SHA256.Create())
        {
            identity = BitConverter.ToString(hash.ComputeHash(System.Text.Encoding.UTF8.GetBytes(source))).Replace("-", "") + "_";
        }
        var imports = new LegacyBindings(cancellationToken, identity);
        // Rewrite imports first so the UTF-8 pass can distinguish forward delegates from callbacks.
        var root = new UTF8Marshalling(cancellationToken).Visit(imports.Visit(original))!;
        var generated = "// <auto-generated/>\n" + root.NormalizeWhitespace().ToFullString();
        Validate(CSharpSyntaxTree.ParseText(generated, options, cancellationToken: cancellationToken), cancellationToken);
        count = imports.Count;
        return generated;
    }

    /// <summary>
    /// Rejects syntax errors before invalid declarations can enter the legacy compilation.
    /// </summary>
    private static void Validate(SyntaxTree tree, CancellationToken cancellationToken)
    {
        var error = tree.GetDiagnostics(cancellationToken).FirstOrDefault(d => d.Severity == DiagnosticSeverity.Error);

        if (error != null)
        {
            throw new BindingGenerationException(error.GetMessage(System.Globalization.CultureInfo.InvariantCulture), error.Location);
        }
    }

    /// <summary>
    /// Assigns explicit string ownership and rejects signatures that need a dedicated native-layout bridge.
    /// </summary>
    private sealed class UTF8Marshalling : CSharpSyntaxRewriter
    {
        /// <summary>Allows the compiler host to cancel a traversal when its input changes.</summary>
        private readonly CancellationToken cancellationToken;

        /// <summary>Creates a cancellable marshalling validator and transformer.</summary>
        internal UTF8Marshalling(CancellationToken cancellationToken)
        {
            this.cancellationToken = cancellationToken;
        }

        /// <summary>Checks cancellation before traversing each source node.</summary>
        public override SyntaxNode? Visit(SyntaxNode? node)
        {
            cancellationToken.ThrowIfCancellationRequested();
            return base.Visit(node);
        }

        /// <summary>Validates original import signatures before generated delegates change source offsets.</summary>
        public override SyntaxNode? VisitMethodDeclaration(MethodDeclarationSyntax node)
        {
            if (node.Modifiers.Any(SyntaxKind.ExternKeyword))
            {
                ValidateStrings(node.ReturnType, node.ParameterList, node);
            }

            return base.VisitMethodDeclaration(node);
        }

        /// <summary>
        /// Rejects string results and by-reference strings whose ownership cannot be inferred safely.
        /// </summary>
        public override SyntaxNode? VisitDelegateDeclaration(DelegateDeclarationSyntax node)
        {
            ValidateStrings(node.ReturnType, node.ParameterList, node);
            return base.VisitDelegateDeclaration(node);
        }

        /// <summary>Rejects signatures whose returned or by-reference string ownership is unspecified.</summary>
        private static void ValidateStrings(TypeSyntax returnType, ParameterListSyntax parameters, SyntaxNode node)
        {
            bool IsString(TypeSyntax? type) => type?.ToString() is "string" or "System.String";

            // Return and ref/out strings need allocation and release rules that attributes cannot infer.
            if (IsString(returnType) || parameters.Parameters.Any(p => IsString(p.Type) && p.Modifiers.Count != 0))
            {
                throw new BindingGenerationException("String results and ref/out strings need an explicit ownership bridge.", node.GetLocation());
            }
        }

        /// <summary>
        /// Replaces UTF-8 parameter marshalling while preserving descriptive fields and unrelated syntax.
        /// </summary>
        public override SyntaxNode? VisitAttribute(AttributeSyntax node)
        {
            if (node.Name.ToString() != "MarshalAs" || node.ArgumentList?.Arguments.FirstOrDefault()?.Expression.ToString() != "UnmanagedType.LPUTF8Str")
            {
                return base.VisitAttribute(node);
            }

            if (node.ArgumentList.Arguments.Count != 1)
            {
                throw new BindingGenerationException("Unexpected UTF-8 marshalling options.", node.GetLocation());
            }

            string replacement;

            if (node.Ancestors().OfType<FieldDeclarationSyntax>().Any())
            {
                var structure = node.Ancestors().OfType<StructDeclarationSyntax>().FirstOrDefault()?.Identifier.ValueText;

                if (structure is not ("error_t" or "class_t"))
                {
                    throw new BindingGenerationException($"UTF-8 field in {structure} needs an explicit native-layout bridge.", node.GetLocation());
                }

                // These public structures are descriptive; native calls use explicit pointer layouts.
                replacement = "((UnmanagedType)48)";
            }
            else
            {
                var callback = node.Ancestors().OfType<DelegateDeclarationSyntax>().FirstOrDefault();
                // Generated __Legacy delegates own input buffers; user callbacks borrow HDF5 memory.
                var borrowed = callback != null && !callback.Identifier.ValueText.StartsWith("__Legacy", StringComparison.Ordinal);
                replacement = "(UnmanagedType.CustomMarshaler, MarshalTypeRef = typeof(UTF8Marshaler)" +
                    (borrowed ? ", MarshalCookie = \"borrowed\")" : ")");
            }

            // Change only attribute syntax; documentation and string literals remain untouched.
            return node.WithArgumentList(SyntaxFactory.ParseAttributeArgumentList(replacement));
        }
    }
}
