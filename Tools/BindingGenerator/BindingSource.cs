using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

internal static class BindingSource
{
    private static readonly CSharpParseOptions Options = new CSharpParseOptions(LanguageVersion.Latest)
        .WithPreprocessorSymbols("NETSTANDARD", "NETSTANDARD2_0");

    internal static string Generate(string source, out int count, IEnumerable<string>? symbols = null)
    {
        var options = symbols == null ? Options : Options.WithPreprocessorSymbols(symbols);
        var tree = CSharpSyntaxTree.ParseText(source, options);
        Validate(tree);
        var imports = new LegacyBindings();
        var root = new Utf8Marshalling().Visit(imports.Visit(tree.GetRoot()))!;
        string generated = "// <auto-generated/>\n" + root.NormalizeWhitespace().ToFullString();
        Validate(CSharpSyntaxTree.ParseText(generated, options));
        count = imports.Count;
        return generated;
    }

    private static void Validate(SyntaxTree tree)
    {
        var errors = tree.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToArray();

        if (errors.Length != 0)
        {
            throw new InvalidOperationException(string.Join(Environment.NewLine, errors.Select(e => e.ToString())));
        }
    }

    private sealed class Utf8Marshalling : CSharpSyntaxRewriter
    {
        public override SyntaxNode? VisitDelegateDeclaration(DelegateDeclarationSyntax node)
        {
            bool IsString(TypeSyntax? type) => type?.ToString() is "string" or "System.String";

            if (IsString(node.ReturnType) || node.ParameterList.Parameters.Any(p => IsString(p.Type) && p.Modifiers.Count != 0))
            {
                throw new InvalidOperationException("String results and ref/out strings need an explicit ownership bridge.");
            }

            return base.VisitDelegateDeclaration(node);
        }

        public override SyntaxNode? VisitAttribute(AttributeSyntax node)
        {
            if (node.Name.ToString() != "MarshalAs" || node.ArgumentList?.Arguments.FirstOrDefault()?.Expression.ToString() != "UnmanagedType.LPUTF8Str")
            {
                return base.VisitAttribute(node);
            }

            if (node.ArgumentList.Arguments.Count != 1)
            {
                throw new InvalidOperationException("Unexpected UTF-8 marshalling options.");
            }

            string replacement;

            if (node.Ancestors().OfType<FieldDeclarationSyntax>().Any())
            {
                string? structure = node.Ancestors().OfType<StructDeclarationSyntax>().FirstOrDefault()?.Identifier.ValueText;

                if (structure is not ("error_t" or "class_t"))
                {
                    throw new InvalidOperationException($"UTF-8 field in {structure} needs an explicit native-layout bridge.");
                }

                // These public structures are descriptive; native calls use explicit pointer layouts.
                replacement = "((UnmanagedType)48)";
            }
            else
            {
                var callback = node.Ancestors().OfType<DelegateDeclarationSyntax>().FirstOrDefault();
                bool borrowed = callback != null && !callback.Identifier.ValueText.StartsWith("__Legacy", StringComparison.Ordinal);
                replacement = "(UnmanagedType.CustomMarshaler, MarshalTypeRef = typeof(Utf8Marshaler)" +
                    (borrowed ? ", MarshalCookie = \"borrowed\")" : ")");
            }

            // Change only attribute syntax; documentation and string literals remain untouched.
            return node.WithArgumentList(SyntaxFactory.ParseAttributeArgumentList(replacement));
        }
    }
}
